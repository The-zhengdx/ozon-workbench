-- 素材加工任务与 Codex 会话事件。
-- 服务启动时 Ent Schema.Create 也会创建这两张表；本文件便于审阅。

CREATE TABLE IF NOT EXISTS public.workbench_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id bigint NOT NULL,
    category_node_id bigint NOT NULL DEFAULT 0,
    description_category_id bigint NOT NULL,
    type_id bigint NOT NULL,
    language character varying NOT NULL DEFAULT 'ZH_HANS',
    type_name character varying NOT NULL DEFAULT '',
    type_path jsonb,
    master_sku character varying NOT NULL,
    supplier_url character varying NOT NULL DEFAULT '',
    zip_filename character varying NOT NULL DEFAULT '',
    zip_local_path character varying NOT NULL DEFAULT '',
    auto_text_approve boolean NOT NULL DEFAULT false,
    auto_visual_approve boolean NOT NULL DEFAULT false,
    text_approved boolean NOT NULL DEFAULT false,
    text_approved_auto boolean NOT NULL DEFAULT false,
    visual_approved boolean NOT NULL DEFAULT false,
    visual_approved_auto boolean NOT NULL DEFAULT false,
    status character varying NOT NULL DEFAULT 'RUNNING',
    phase character varying NOT NULL DEFAULT 'extract',
    codex_session_id character varying NOT NULL DEFAULT '',
    revision bigint NOT NULL DEFAULT 1,
    missing_fields jsonb NOT NULL DEFAULT '[]'::jsonb,
    input_values jsonb NOT NULL DEFAULT '{}'::jsonb,
    sub_skus jsonb NOT NULL DEFAULT '[]'::jsonb,
    text_draft jsonb NOT NULL DEFAULT '{}'::jsonb,
    visual_plan jsonb NOT NULL DEFAULT '{}'::jsonb,
    attributes_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    prompt_template text NOT NULL DEFAULT '',
    rendered_prompt text NOT NULL DEFAULT '',
    error_message character varying NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

CREATE INDEX IF NOT EXISTS workbenchtask_shop_id_status ON public.workbench_tasks (shop_id, status);
CREATE INDEX IF NOT EXISTS workbenchtask_status ON public.workbench_tasks (status);

CREATE TABLE IF NOT EXISTS public.task_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    session_id character varying NOT NULL DEFAULT '',
    seq bigint NOT NULL,
    role character varying NOT NULL,
    stage character varying NOT NULL DEFAULT '',
    content text NOT NULL DEFAULT '',
    tool_call_id character varying NOT NULL DEFAULT '',
    resource_ref character varying NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS taskevent_task_id_seq ON public.task_events (task_id, seq);
CREATE INDEX IF NOT EXISTS taskevent_shop_id_task_id ON public.task_events (shop_id, task_id);
