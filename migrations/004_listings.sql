-- 按可售 SKU 刊登：分组、版本、媒体、导入批次和分仓库存。
-- 服务启动时 Ent Schema.Create 也会创建这些表；本文件便于审阅。

CREATE TABLE IF NOT EXISTS public.listing_products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id bigint NOT NULL,
    task_id bigint NOT NULL DEFAULT 0,
    master_sku character varying NOT NULL,
    supplier_url character varying NOT NULL DEFAULT '',
    description_category_id bigint NOT NULL DEFAULT 0,
    type_id bigint NOT NULL DEFAULT 0,
    type_name character varying NOT NULL DEFAULT '',
    type_path jsonb,
    language character varying NOT NULL DEFAULT 'ZH_HANS',
    attributes_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    codex_session_id character varying NOT NULL DEFAULT '',
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS listingproduct_shop_id_task_id_master_sku
    ON public.listing_products (shop_id, task_id, master_sku);

CREATE TABLE IF NOT EXISTS public.listing_skus (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id bigint NOT NULL,
    product_id bigint NOT NULL,
    task_id bigint NOT NULL DEFAULT 0,
    offer_id character varying NOT NULL,
    master_sku character varying NOT NULL DEFAULT '',
    supplier_variant_ref character varying NOT NULL DEFAULT '',
    variant_specs character varying NOT NULL DEFAULT '',
    category_label character varying NOT NULL DEFAULT '',
    current_version bigint NOT NULL DEFAULT 1,
    publish_status character varying NOT NULL DEFAULT '待完善',
    platform_status character varying NOT NULL DEFAULT '待回读',
    platform_reason character varying NOT NULL DEFAULT '',
    last_imported_version bigint NOT NULL DEFAULT 0,
    ozon_product_id bigint NOT NULL DEFAULT 0,
    ozon_sku bigint NOT NULL DEFAULT 0,
    last_checked_at timestamp NULL,
    currency_code character varying NOT NULL DEFAULT '',
    price character varying NOT NULL DEFAULT '',
    title_ru character varying NOT NULL DEFAULT '',
    primary_image character varying NOT NULL DEFAULT '',
    preview_path character varying NOT NULL DEFAULT '',
    last_error character varying NOT NULL DEFAULT '',
    codex_attempted boolean NOT NULL DEFAULT false,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS listingsku_shop_id_offer_id ON public.listing_skus (shop_id, offer_id);
CREATE INDEX IF NOT EXISTS listingsku_shop_id_publish_status_id ON public.listing_skus (shop_id, publish_status, id);

CREATE TABLE IF NOT EXISTS public.listing_sku_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_sku_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    version bigint NOT NULL,
    source character varying NOT NULL DEFAULT 'draft',
    codex_item_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    item_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    contract_version character varying NOT NULL DEFAULT '',
    validation_json jsonb NOT NULL DEFAULT '[]'::jsonb,
    valid boolean NOT NULL DEFAULT false,
    created_at timestamp NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS listingrevision_listing_sku_id_version
    ON public.listing_sku_revisions (listing_sku_id, version);

CREATE TABLE IF NOT EXISTS public.listing_media (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_sku_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    role character varying NOT NULL DEFAULT 'image',
    local_path character varying NOT NULL DEFAULT '',
    storage_key character varying NOT NULL DEFAULT '',
    public_url character varying NOT NULL DEFAULT '',
    public_key character varying NOT NULL DEFAULT '',
    status character varying NOT NULL DEFAULT 'local',
    error_message character varying NOT NULL DEFAULT '',
    attempts bigint NOT NULL DEFAULT 0,
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL
);

CREATE TABLE IF NOT EXISTS public.publish_batches (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id bigint NOT NULL,
    idempotency_key character varying NOT NULL,
    selection_hash character varying NOT NULL DEFAULT '',
    status character varying NOT NULL DEFAULT 'pending',
    created_at timestamp NOT NULL,
    updated_at timestamp NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS publishbatch_shop_id_idempotency_key
    ON public.publish_batches (shop_id, idempotency_key);

CREATE TABLE IF NOT EXISTS public.publish_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    chunk_index bigint NOT NULL DEFAULT 0,
    request_body_json jsonb NOT NULL DEFAULT '{}'::jsonb,
    task_id character varying NOT NULL DEFAULT '',
    status character varying NOT NULL DEFAULT 'pending',
    error_message character varying NOT NULL DEFAULT '',
    sent_at timestamp NULL,
    finished_at timestamp NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS publishrequest_batch_id_chunk_index
    ON public.publish_requests (batch_id, chunk_index);

CREATE TABLE IF NOT EXISTS public.publish_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL,
    batch_id bigint NOT NULL,
    listing_sku_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    version bigint NOT NULL,
    offer_id character varying NOT NULL,
    result_status character varying NOT NULL DEFAULT 'pending',
    ozon_product_id bigint NOT NULL DEFAULT 0,
    ozon_sku bigint NOT NULL DEFAULT 0,
    error_code character varying NOT NULL DEFAULT '',
    error_detail character varying NOT NULL DEFAULT ''
);

CREATE UNIQUE INDEX IF NOT EXISTS publishitem_batch_id_listing_sku_id
    ON public.publish_items (batch_id, listing_sku_id);

CREATE TABLE IF NOT EXISTS public.sku_warehouse_stocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_sku_id bigint NOT NULL,
    shop_id bigint NOT NULL,
    warehouse_id bigint NOT NULL,
    target_qty bigint NOT NULL DEFAULT 0,
    platform_qty bigint NOT NULL DEFAULT -1,
    sync_status character varying NOT NULL DEFAULT '',
    sync_message character varying NOT NULL DEFAULT '',
    synced_at timestamp NULL,
    updated_at timestamp NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS skuwarehousestock_listing_sku_id_warehouse_id
    ON public.sku_warehouse_stocks (listing_sku_id, warehouse_id);
